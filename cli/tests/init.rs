use std::{fs, process::Command};

#[test]
fn scaffold_build_target_and_deploy_entry_match_cargo_component_output() {
    let root = std::env::temp_dir().join(format!("pushit-init-target-{}", std::process::id()));
    fs::create_dir(&root).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_pushit"))
        .args(["init", "hello-app"])
        .current_dir(&root)
        .output()
        .unwrap();
    assert!(output.status.success(), "{output:?}");
    let app = root.join("hello-app");
    let manifest: serde_yaml::Value =
        serde_yaml::from_str(&fs::read_to_string(app.join("pushit.yaml")).unwrap()).unwrap();
    let config: toml::Value =
        toml::from_str(&fs::read_to_string(app.join("fn/.cargo/config.toml")).unwrap()).unwrap();
    let target = config["build"]["target"].as_str().unwrap();
    // cargo-component 0.21.1 adapts the wasip1 module in this directory into
    // a component; requesting wasip2 instead also builds wasip1, not the entry
    // path previously generated by init. No WIT registry access is needed here.
    assert_eq!(target, "wasm32-wasip1");
    assert_eq!(
        manifest["build"]["fn"].as_str().unwrap(),
        format!("cd fn && cargo component build --release --target {target}")
    );
    assert_eq!(
        manifest["entry"].as_str().unwrap(),
        format!("fn/target/{target}/release/hello_app.wasm")
    );
    // Changing the core compilation target must not change the component API.
    let wit = fs::read_to_string(app.join("fn/wit/world.wit")).unwrap();
    assert!(wit.contains("import wasi:cli/environment@0.2.0;"));
    assert!(wit.contains("export wasi:http/incoming-handler@0.2.0;"));
    let cargo = fs::read_to_string(app.join("fn/Cargo.toml")).unwrap();
    assert!(cargo.contains("\"wasi:http\" = \"=0.2.0\""));
    assert!(cargo.contains("\"wasi:cli\" = \"=0.2.0\""));
    fs::remove_dir_all(root).unwrap();
}
