use std::{fs, process::Command};

#[test]
fn scaffold_is_standalone_inside_and_outside_a_cargo_workspace() {
    let root = std::env::temp_dir().join(format!("pushit-init-workspace-{}", std::process::id()));
    fs::create_dir(&root).unwrap();
    for nested in [false, true] {
        for named in [false, true] {
            let parent = root.join(format!("nested-{nested}-named-{named}"));
            fs::create_dir(&parent).unwrap();
            let workspace = b"[workspace]\nresolver = \"2\"\nmembers = []\n";
            if nested {
                fs::write(parent.join("Cargo.toml"), workspace).unwrap();
            }
            let current = parent.join("current-app");
            fs::create_dir(&current).unwrap();
            let args = if named {
                vec!["init", "hello-app"]
            } else {
                vec!["init"]
            };
            let init = || {
                Command::new(env!("CARGO_BIN_EXE_pushit"))
                    .args(&args)
                    .current_dir(&current)
                    .output()
                    .unwrap()
            };
            let output = init();
            assert!(output.status.success(), "{output:?}");
            let app = if named {
                current.join("hello-app")
            } else {
                current.clone()
            };
            let manifest = app.join("fn/Cargo.toml");
            let metadata = Command::new(env!("CARGO"))
                .args([
                    "metadata",
                    "--no-deps",
                    "--format-version",
                    "1",
                    "--offline",
                    "--manifest-path",
                ])
                .arg(&manifest)
                .current_dir(&app)
                .output()
                .unwrap();
            assert!(metadata.status.success(), "{metadata:?}");
            let metadata: serde_json::Value = serde_json::from_slice(&metadata.stdout).unwrap();
            assert_eq!(
                metadata["workspace_root"].as_str().unwrap(),
                app.join("fn").canonicalize().unwrap().to_str().unwrap()
            );
            // Re-running init must reject existing apps without overwriting edits.
            fs::write(app.join("fn/src/lib.rs"), "// user changes\n").unwrap();
            let original_manifest = fs::read(&manifest).unwrap();
            let output = init();
            assert!(!output.status.success(), "{output:?}");
            assert!(String::from_utf8_lossy(&output.stderr).contains("pushit.yaml already exists"));
            assert_eq!(fs::read(&manifest).unwrap(), original_manifest);
            assert_eq!(
                fs::read_to_string(app.join("fn/src/lib.rs")).unwrap(),
                "// user changes\n"
            );
            if nested {
                assert_eq!(fs::read(parent.join("Cargo.toml")).unwrap(), workspace);
            }
        }
    }
    fs::remove_dir_all(root).unwrap();
}

#[test]
fn scaffold_build_target_and_deploy_entry_match_cargo_component_output() {
    let root = std::env::temp_dir().join(format!("pushit-init-target-{}", std::process::id()));
    fs::create_dir(&root).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_pushit"))
        .args(["init", "hello-app"])
        .current_dir(&root)
        .output()
        .unwrap();
    assert!(output.status.success(), "{output:?}");
    let stdout = String::from_utf8(output.stdout).unwrap();
    assert!(stdout.contains("pushit --dev --server http://127.0.0.1:9100 deploy"));
    assert!(stdout.contains("authorized profile"));
    assert!(!stdout.contains("pushit --dev deploy"));
    let app = root.join("hello-app");
    let manifest: serde_yaml::Value =
        serde_yaml::from_str(&fs::read_to_string(app.join("pushit.yaml")).unwrap()).unwrap();
    let config: toml::Value =
        toml::from_str(&fs::read_to_string(app.join("fn/.cargo/config.toml")).unwrap()).unwrap();
    let target = config["build"]["target"].as_str().unwrap();
    // cargo-component 0.21.1 adapts the wasip1 module in this directory into
    // a component; requesting wasip2 instead also builds wasip1, not the entry
    // path previously generated by init. No WIT registry access is needed here.
    assert_eq!(target, "wasm32-wasip1");
    assert_eq!(
        manifest["build"]["fn"].as_str().unwrap(),
        format!("cd fn && cargo component build --release --target {target}")
    );
    assert_eq!(
        manifest["entry"].as_str().unwrap(),
        format!("fn/target/{target}/release/hello_app.wasm")
    );
    // Changing the core compilation target must not change the component API.
    let wit = fs::read_to_string(app.join("fn/wit/world.wit")).unwrap();
    assert!(wit.contains("import wasi:cli/environment@0.2.0;"));
    assert!(wit.contains("export wasi:http/incoming-handler@0.2.0;"));
    let cargo = fs::read_to_string(app.join("fn/Cargo.toml")).unwrap();
    let cargo: toml::Value = toml::from_str(&cargo).unwrap();
    let deps = cargo["package"]["metadata"]["component"]["target"]["dependencies"]
        .as_table()
        .unwrap();
    assert_eq!(deps.len(), 4);
    for package in ["http", "cli", "io", "clocks"] {
        assert_eq!(
            deps[&format!("wasi:{package}")]["path"].as_str().unwrap(),
            format!("wit/deps/{package}")
        );
        let source = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../examples/hello/fn/wit/deps")
            .join(package);
        let dest = app.join("fn/wit/deps").join(package);
        let files: Vec<_> = fs::read_dir(&dest)
            .unwrap()
            .map(|entry| entry.unwrap().path())
            .collect();
        assert_eq!(
            files.len(),
            match package {
                "http" | "clocks" => 3,
                "cli" => 2,
                "io" => 4,
                _ => unreachable!(),
            }
        );
        for file in files {
            assert_eq!(
                fs::read(&file).unwrap(),
                fs::read(source.join(file.file_name().unwrap())).unwrap()
            );
        }
    }
    assert_eq!(
        fs::read_to_string(app.join("fn/wit/NOTICE.md")).unwrap(),
        include_str!("../../examples/hello/fn/wit/NOTICE.md")
    );
    fs::remove_dir_all(root).unwrap();
}
